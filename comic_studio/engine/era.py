# comic_studio/engine/era.py
"""时代背景检测：限定式朝代关键词扫描（2026-08-25 需求——明确朝代则资产/分镜
提示词自动加时代限制，防"古风肚兜生成成现代胸罩"类时代漂移）。

只认限定式提及（大唐/唐朝/北宋/民国…），裸字（唐三/汉子/清明/元宝）不误报。
2026-09-20 猫物语判例：「大X」缩写形会撞进常用词——「孤陋寡闻不大清楚」的
子串「大清」把 44 万字日本现代小说整本判成「中国清代」，时代限制句反向毒害
全部图像提示词。缩写形加负向先行挡已知常用词续字；未列尽的续字仍可能误报，
清洗法=重分析（机器标记自动刷新）或 PATCH era 空串。
"""
import re

# 按时间序；同文多朝代时取提及次数最多者（穿越文以主场景为准不保证，PATCH 可改）
# 负向先行=常用词续字黑名单：大清楚/大清早/大清白/大清单、大明白/大明星、
# 大元素/大元帅/大元凶、大汉子、五代同堂/五代人、移民国家/人民国家
_GROUPS = [
    ("中国秦代", r"大秦|秦朝|秦代"),
    ("中国汉代", r"大汉(?!子)|西汉|东汉|汉朝|汉代"),
    ("中国汉末三国时期", r"三国"),
    ("中国魏晋时期", r"西晋|东晋|两晋|晋朝|晋代"),
    ("中国南北朝时期", r"南北朝"),
    ("中国隋代", r"大隋|隋朝|隋代"),
    ("中国唐代", r"大唐|盛唐|晚唐|中唐|唐初|唐朝|唐代"),
    ("中国五代十国时期", r"五代十国|五代(?!同|人)"),
    ("中国宋代", r"大宋|北宋|南宋|宋朝|宋代"),
    ("中国元代", r"大元(?!素|帅|凶)|蒙元|元朝|元代"),
    ("中国明代", r"大明(?!白|星)|明朝|明代"),
    ("中国清代", r"大清(?!楚|白|早|单)|满清|清朝|清代"),
    ("中华民国时期", r"民国(?!家)"),
]

ERA_SUFFIX = "时代风格：{era}，人物服饰、发型、器物、建筑均须符合该时代形制，禁止现代元素"

# 现代/当代/未来题材不得注「禁止现代元素」（自相矛盾）
_MODERN_ERA_RE = re.compile(r"现代|当代|未来")

# detect_era 的闭集标签——重分析时据此区分「机器检测值」（随文本刷新）
# 与「人工纠错值」（如 日本现代，不动）
ERA_LABELS = frozenset(label for label, _ in _GROUPS)


def detect_era(text: str) -> str:
    """全文扫描限定式朝代提及，取次数最多者；无明确朝代返回空串。"""
    best, best_n = "", 0
    for label, pat in _GROUPS:
        n = len(re.findall(pat, text))
        if n > best_n:
            best, best_n = label, n
    return best


def era_suffix(era: str) -> str:
    """时代限制句：古代朝代=禁现代元素；现代/当代/未来=禁古装与时代错位
    （2026-09-20 用户手改「日本现代」撞「禁止现代元素」判例）；空串=空。"""
    era = (era or "").strip()
    if not era:
        return ""
    if _MODERN_ERA_RE.search(era):
        return (f"时代风格：{era}，人物服饰、发型、器物、建筑均须符合该时代形制，"
                "禁止古装与时代错位元素")
    return ERA_SUFFIX.format(era=era)
